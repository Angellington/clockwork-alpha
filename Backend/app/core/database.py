from collections.abc import Generator

from psycopg import Connection, connect
from psycopg.rows import dict_row

from app.core.config import settings


def open_database() -> Connection:
    if not settings.database_url:
        raise RuntimeError("DATABASE_URL or DB_* variables are not configured")

    return connect(settings.database_url, row_factory=dict_row)


def get_db() -> Generator[Connection, None, None]:
    db = open_database()

    try:
        yield db
    finally:
        db.close()


def check_database_connection() -> bool:
    with open_database() as db:
        with db.cursor() as cursor:
            cursor.execute("SELECT 1")
            cursor.fetchone()

    return True


def ensure_quarantine_schema() -> None:
    with open_database() as db:
        with db.cursor() as cursor:
            cursor.execute(
                """
                CREATE TABLE IF NOT EXISTS quarantine_videos (
                    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    youtube_video_id text NOT NULL,
                    url text NOT NULL,
                    title text NOT NULL,
                    description text,
                    channel text,
                    thumbnail_url text,
                    duration_seconds integer,
                    published_at timestamptz,
                    watched boolean NOT NULL DEFAULT false,
                    watched_at timestamptz,
                    created_at timestamptz NOT NULL DEFAULT now(),
                    updated_at timestamptz NOT NULL DEFAULT now()
                )
                """
            )
            cursor.execute(
                """
                CREATE TABLE IF NOT EXISTS quarantine_playlists (
                    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    name text NOT NULL,
                    description text,
                    channel text,
                    source text NOT NULL DEFAULT 'manual',
                    source_playlist_id text,
                    source_url text,
                    imported_at timestamptz,
                    created_at timestamptz NOT NULL DEFAULT now(),
                    updated_at timestamptz NOT NULL DEFAULT now(),
                    CONSTRAINT quarantine_playlists_source_check
                        CHECK (source IN ('manual', 'youtube'))
                )
                """
            )
            cursor.execute(
                """
                CREATE TABLE IF NOT EXISTS quarantine_playlist_items (
                    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    playlist_id integer NOT NULL
                        REFERENCES quarantine_playlists(id) ON DELETE CASCADE,
                    video_id integer
                        REFERENCES quarantine_videos(id) ON DELETE CASCADE,
                    child_playlist_id integer
                        REFERENCES quarantine_playlists(id) ON DELETE CASCADE,
                    position integer NOT NULL DEFAULT 0,
                    created_at timestamptz NOT NULL DEFAULT now(),
                    CONSTRAINT quarantine_playlist_items_one_resource_check
                        CHECK (
                            (video_id IS NOT NULL AND child_playlist_id IS NULL)
                            OR (video_id IS NULL AND child_playlist_id IS NOT NULL)
                        )
                )
                """
            )
            cursor.execute(
                """
                ALTER TABLE quarantine_playlists
                ADD COLUMN IF NOT EXISTS description text
                """
            )
            cursor.execute(
                """
                CREATE UNIQUE INDEX IF NOT EXISTS quarantine_videos_youtube_video_id_idx
                ON quarantine_videos (youtube_video_id)
                """
            )
            cursor.execute(
                """
                CREATE UNIQUE INDEX IF NOT EXISTS quarantine_playlists_youtube_source_idx
                ON quarantine_playlists (source_playlist_id)
                WHERE source = 'youtube' AND source_playlist_id IS NOT NULL
                """
            )
            cursor.execute(
                """
                CREATE UNIQUE INDEX IF NOT EXISTS quarantine_playlist_items_video_idx
                ON quarantine_playlist_items (playlist_id, video_id)
                WHERE video_id IS NOT NULL
                """
            )
            cursor.execute(
                """
                CREATE UNIQUE INDEX IF NOT EXISTS quarantine_playlist_items_child_playlist_idx
                ON quarantine_playlist_items (playlist_id, child_playlist_id)
                WHERE child_playlist_id IS NOT NULL
                """
            )
        db.commit()
